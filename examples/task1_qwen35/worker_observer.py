"""Optional worker-side diagnostics; never active in primary timing runs."""

from __future__ import annotations

import functools
import json
import os
import time
from pathlib import Path

from examples.task1_qwen35.common import save_json

_installed_control: str | None = None


def weight_audit(
    model, checkpoint_tensors: list[dict], loaded_params: set[str]
) -> dict:
    """Compare the loader's names with actual parameter storage, including ties."""
    named = dict(model.named_parameters(remove_duplicate=False))
    storage_groups = {}
    parameters = {}
    for name, parameter in named.items():
        # Sharing a storage allocation alone is insufficient: require the same
        # offset, layout and dtype, so distinct fused views cannot hide a miss.
        identity = (
            str(parameter.device),
            parameter.untyped_storage().data_ptr(),
            parameter.storage_offset(),
            tuple(parameter.shape),
            tuple(parameter.stride()),
            str(parameter.dtype),
        )
        if parameter.device.type == "meta" or parameter.numel() == 0:
            identity = (*identity, name)
        group = storage_groups.setdefault(identity, len(storage_groups))
        parameters[name] = {
            "shape": list(parameter.shape),
            "numel": parameter.numel(),
            "device": str(parameter.device),
            "dtype": str(parameter.dtype),
            "storage_group": group,
        }
    loaded_groups = {
        parameters[name]["storage_group"]
        for name in loaded_params
        if name in parameters
    }
    text_names = [
        name for name in parameters if "visual" not in name and "mtp" not in name
    ]
    missing = []
    tied = {}
    for name in text_names:
        if name in loaded_params:
            parameters[name]["coverage"] = "loaded_name"
        elif parameters[name]["storage_group"] in loaded_groups:
            parameters[name]["coverage"] = "shared_storage"
            tied[name] = sorted(
                other
                for other in loaded_params
                if other in parameters
                and parameters[other]["storage_group"]
                == parameters[name]["storage_group"]
            )
        else:
            parameters[name]["coverage"] = "missing"
            missing.append(name)
    ignored = {
        reason: [item["name"] for item in checkpoint_tensors if reason in item["name"]]
        for reason in ("visual", "mtp", "rotary_emb.inv_freq")
    }
    keys = [item["name"] for item in checkpoint_tensors]
    return {
        "pid": os.getpid(),
        "model_class": type(model).__name__,
        "checkpoint_tensor_count": len(keys),
        "checkpoint_unique_key_count": len(set(keys)),
        "checkpoint_tensors": checkpoint_tensors,
        "loaded_params_count": len(loaded_params),
        "loaded_params": sorted(loaded_params),
        "named_parameter_count_including_aliases": len(parameters),
        "text_parameter_count_including_aliases": len(text_names),
        "parameters": parameters,
        "text_parameters_covered_by_shared_storage": tied,
        "missing_text_parameters": sorted(missing),
        "loaded_names_not_in_named_parameters": sorted(loaded_params - named.keys()),
        "text_parameters_off_npu": [
            name for name in text_names if named[name].device.type != "npu"
        ],
        "ignored_checkpoint_keys": ignored,
        "ignore_policy": "Text-only scope intentionally ignores visual and MTP checkpoint tensors; rotary_emb.inv_freq is regenerated by the original loader.",
        "all_text_parameters_covered": not missing,
        "scope": "Observes the original loader exactly once. Name/storage coverage proves parameter coverage, not that every shard of a fused projection has the correct value; original checkpoint keys are retained for shard review and full-model logits provide numerical validation.",
    }


def install(control_path: str) -> None:
    global _installed_control
    if _installed_control == control_path:
        return
    if _installed_control is not None:
        raise RuntimeError("worker observer already installed for another run")
    import torch
    import torch_npu

    from tokenspeed.runtime.execution.model_runner import ModelRunner
    from tokenspeed.runtime.models.qwen3_5 import Qwen3_5ForConditionalGeneration

    original = ModelRunner.forward
    original_load = Qwen3_5ForConditionalGeneration.load_weights
    sequence = 0
    bound_label = None
    bound_forwards = 0
    profiled = set()
    control = Path(control_path)

    @functools.wraps(original_load)
    def audited_load(self, weights, *args, **kwargs):
        checkpoint_tensors = []

        def observed_weights():
            for name, tensor in weights:
                checkpoint_tensors.append(
                    {
                        "name": name,
                        "shape": list(tensor.shape),
                        "dtype": str(tensor.dtype),
                    }
                )
                yield name, tensor

        loaded = original_load(self, observed_weights(), *args, **kwargs)
        audit = weight_audit(self, checkpoint_tensors, loaded)
        save_json(control.parent / "weight_audit.json", audit)
        if not audit["all_text_parameters_covered"]:
            raise AssertionError(
                f"unloaded text parameters: {audit['missing_text_parameters']}"
            )
        return loaded

    @functools.wraps(original)
    def observed(self, ctx, input_ids, positions, *args, **kwargs):
        nonlocal sequence, bound_label, bound_forwards
        if not control.exists():
            return original(self, ctx, input_ids, positions, *args, **kwargs)
        settings = json.loads(control.read_text())
        if not settings["active"] or ctx.forward_mode.is_idle():
            return original(self, ctx, input_ids, positions, *args, **kwargs)
        if input_ids.device.type != "npu":
            raise AssertionError(f"observed model input is on {input_ids.device}")
        ignored_reason = None
        if settings["label"] != bound_label:
            if ctx.forward_mode.is_extend():
                bound_label = settings["label"]
                bound_forwards = 0
            else:
                ignored_reason = "Control label changed before this request's first extend; previous request overlap forward is still in flight."
        elif bound_forwards >= settings["generation_limit"]:
            ignored_reason = "This request already produced its configured number of forwards; unused overlap forward beyond the last emitted token."
        if ignored_reason is not None:
            # A frontend label is not a request identity. Save explicit evidence
            # instead of assigning a previous request's in-flight work to it.
            prefix = (
                control.parent
                / "worker_excluded"
                / f"{os.getpid()}_{sequence:06d}.json"
            )
            save_json(
                prefix,
                {
                    "pid": os.getpid(),
                    "sequence": sequence,
                    "control_label": settings["label"],
                    "bound_label": bound_label,
                    "phase": ctx.forward_mode.name.lower(),
                    "input_ids": input_ids.detach().cpu().tolist(),
                    "positions": positions.detach().cpu().tolist(),
                    "reason": ignored_reason,
                },
            )
            sequence += 1
            return original(self, ctx, input_ids, positions, *args, **kwargs)
        directory = Path(settings["directory"]) / settings["label"]
        directory.mkdir(parents=True, exist_ok=True)
        phase = ctx.forward_mode.name.lower()
        profile_key = (settings["label"], phase)
        take_profile = settings["profile"] and profile_key not in profiled
        torch.npu.synchronize()
        torch.npu.reset_peak_memory_stats()
        allocated_before = torch.npu.memory_allocated()
        reserved_before = torch.npu.memory_reserved()
        profiler = None
        if take_profile:
            profiler = torch_npu.profiler.profile(
                activities=[
                    torch_npu.profiler.ProfilerActivity.CPU,
                    torch_npu.profiler.ProfilerActivity.NPU,
                ],
                record_shapes=True,
                profile_memory=True,
                with_stack=False,
                on_trace_ready=torch_npu.profiler.tensorboard_trace_handler(
                    str(directory / f"profile_{phase}")
                ),
            )
            profiler.start()
        started = time.perf_counter()
        result = original(self, ctx, input_ids, positions, *args, **kwargs)
        torch.npu.synchronize()
        elapsed = (time.perf_counter() - started) * 1000
        record = {
            "pid": os.getpid(),
            "sequence": sequence,
            "phase": phase,
            "input_tokens": input_ids.numel(),
            "model_forward_ms": elapsed,
            "profiled": take_profile,
            "allocated_before": allocated_before,
            "reserved_before": reserved_before,
            "allocated_after": torch.npu.memory_allocated(),
            "reserved_after": torch.npu.memory_reserved(),
            "max_allocated": torch.npu.max_memory_allocated(),
            "max_reserved": torch.npu.max_memory_reserved(),
        }
        if profiler is not None:
            profiler.stop()
            profiled.add(profile_key)
        prefix = directory / f"{os.getpid()}_{sequence:06d}"
        if settings["capture_logits"]:
            logits = result.next_token_logits
            if logits is None or logits.numel() == 0:
                raise AssertionError("diagnostic forward returned no logits")
            torch.save(
                {
                    "input_ids": input_ids.detach().cpu(),
                    "positions": positions.detach().cpu(),
                    "logits": logits.detach().float().cpu(),
                    "phase": phase,
                },
                prefix.with_suffix(".pt"),
            )
        prefix.with_suffix(".json").write_text(json.dumps(record, indent=2) + "\n")
        sequence += 1
        bound_forwards += 1
        return result

    ModelRunner.forward = observed
    Qwen3_5ForConditionalGeneration.load_weights = audited_load
    _installed_control = control_path
